// Tab Board - 持仓 · 调仓页: 连接 (客户端适配表 live/Clients.hpp 一行一个按钮) / 左栏 控件分组 + 持仓表 (并调仓名单) + 事务日志 / 右栏选中行的行情图
//   左栏小一号字 (kFontScale)、紧凑间距, 一屏放下持仓与调仓两面; 各表格内边距随栏宽收放 (放得下用满, 放不下压到 1px, 仍放不下则长表头折两行)
//   控件分组一行一组, 状态行定高 (不随内容增减, 免得持仓表的按钮在手底下挪):
//     数据: 刷新 / 定时 / 两融条款 / 隐私, 刷新进度; 下单: 委托价 / 买入方式, 最近两单的步骤条;
//     调仓: 普通 / 融资加仓 / 担保减仓 / 名单 / 最小单元 / (融资加仓 · 担保减仓: 卖出总 bar) / 行使比例 (融资加仓: 融资买入; 担保减仓不买, 无) / 执行,
//       试算状态 + 试算表与事务;
//     账户: 现 / 调仓后 / 变动% (总资产 / 持仓市值 / 净资产 / 负债 / 现金 / 可用保证金 / 可融余量 / 杠杆 / 维持担保), 调仓后与现不同的格标色, 变动按该列好坏着色 (好红坏绿)
//   持仓表: 持仓 × 当日成交 × 行情 (live/Board.hpp), 今日清仓的排在后、名称灰; 在当前调仓名单里的名称青.
//     名单里未持有的列在表末 (按排名, 不随排序), 能出的列照持仓出: 总市值、名称、状态、融、调仓金额与成本、折算,
//     可买的 (有行情) 另出买入按钮 (卖出按钮禁用) 与当日% (= 现价 / 昨收 − 1); 这次不入的名称灰.
//     总市值 [亿元, 取整, 格里不写单位] = 本地库最新收盘 (AssetInfo 的 mcap), 紧跟仓位%.
//     点表头排序 (标识与数值列, 三态, 不排 = 帧序; 今日清仓、空值恒在后).
//     状态列: ● 今日成交 · ○ 挂单, 买红卖绿, 悬停看逐笔. 融列与卖出、金额、成本各列取自调仓试算 (试算未出即空).
//     金额 = 现金买,融资买/卖 [万] (卖 = 拖到的股数 × 现价), 买红卖绿 (卖的这只有融资负债: 橙, 回款先还它), 0 占位不着色; 名单股的排名、保证金比例、
//     不补 / 不成单 / 不可买的原因与成本拆分放悬停 (名称、金额、成本格).
//     合计行当日% = 当日盈亏 / 昨净资产 (现金 + 总市值 − 负债 − 当日盈亏).
//   下单: 买卖镜像三档滑点各一按钮 (自左而右 买 15W/5W/1W、卖 1W/5W/15W), 填充 = 该额的滑点色
//     (绿 < kSlipOk ≤ 黄 < kSlipHi ≤ 红, 竞价 / 无行情不填); 悬停看 价格 (micro price) / 预期成交价 / 滑点 bp / 成本 (元).
//     默认锁住 (勾上该列表头的「解锁」才下得了单), 解锁后点了直接下, 不再确认;
//     买入方式只管买入 (默认融资), 卖出一律担保品卖出; 有事务在跑即都不收
//   卖出滑杆按股数线性走 (0 … 全部可卖), 拖动时就地 snap 到能成单的股数 (live::rebal::snap): 0 不卖、
//     first 起按步长递增或连同零股 (first 够起买股数且够最小调仓单元)、全部可卖 (够最小调仓单元才有; 融资加仓 / 担保减仓不管), 取最近的;
//     本只有融资负债且在卖即滑块标橙 (担保品卖出回款先还本只负债, 见 live/Rebal.hpp「卖出还款」)
//   卖出总 bar (融资加仓 / 担保减仓) 与各只滑杆双向同步 (口径见 Hold::full / base): 拖总 bar = 要卖的各持仓卖同一比例、至多卖满 (全部可卖);
//     融资加仓卖有自有部分的 (混合持仓也整只卖, 只卖自有部分做不到; 纯融资的不卖), 担保减仓卖非融资标的 (融资标的不卖);
//     按能成单的档向下取 (覆盖各只; 没卖满的照守最小单元; 剩下不足一个最小单元且已过半的即卖满, 不留碎股);
//     总 bar 显示 = Σ min(卖出, 卖满) 额 / Σ 其持仓额, 由各只滑杆算出; 拖不过上限 Σ 可卖额 / Σ 持仓额, 上限 < 100% (今日买入的不可卖) 即标色: 本次做不满
//   调仓: 名单先融资标的、后其余, 各按排名入选, 等权补齐; 试算与执行的口径见 live/Rebal.hpp, 事务的步骤见 LiveHub.hpp
//   行情图 = Market 的个股面板 (QuotesPanel), 本地资产库就绪才有
//   隐私 (LiveHub::priv): 代码 / 名称 / 状态 / 盈亏 / 市值各列 (含合计, 合计只数照显)、账户对照与试算摘要的金额、
//     名单股的代码 / 名称 / 调仓金额、各单与挂单的代码名称、事务日志、行情图标题遮成 kMask; 比例、只数、下单与卖出各列照显
