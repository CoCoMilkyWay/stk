// Tree — 发给 agent 的上下文: 时间线的纯函数 (不留对话态; 载入 / 回退 / 续接后照时间线重算即是)
// =============================================================================
//   一次请求 = system (一段会话不变, Chat 定) + TurnsOf(时间线). 本条 = 末条往前跳过重发要求后的那条 (第 c 条):
//     c = 1   user 首条
//     c > 1   user 首条 + 研究树 (第 1..c−2 轮的执行) → assistant 第 c−1 轮的回复原文 → user 本条 (第 c−1 轮各调用的原文 + 假设板 + 下一步)
//     重发中  其后接 (被退回的回复, 重发要求) 各一对, 末条 = 最近的重发要求; 收到合格回复后这几对不再出现
//     各条随附的插话跟着它那条消息; 那条收进研究树后, 插话留在树的记录节
//   研究树 = 已收起的执行, 按节点组织 (调用编号 R<轮>#<序> 照旧, judge 引得到); 原文只在交回那条消息里给一次, 此后按结果类型 (ToolDef::fold) 收起:
//     假设     每个一节 (按假设板序), 各步按调用序: 在做的 = 预测四栏 + 各次判定的结论 (最近一次另带 why / better_feature / next) + 证据调用一行 + 变体一行结局;
//              结案的 (落空 / 变体用完且已判) = 标题 + 判定, 早先的判定只留一行, 最近一次留结论
//     其余各步 没挂到假设上的观察 / 查询 / 回测 (没做成的附原因首行): 只留调用一行
//     记录     提交 / 全局记录 / 问答 / finish (结果原样) + 随各条消息的研究员插话, 按时序
// =============================================================================

